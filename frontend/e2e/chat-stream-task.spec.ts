import { test, expect } from "@playwright/test";

test("stream appears before completion, replays after refresh, natural task needs review", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 950 });
  await page.goto("/");
  await page.getByRole("button", { name: "助手", exact: true }).click();
  await page.getByLabel("给助手的消息").fill("流式测试");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  const answer = page.locator(".message.assistant");
  await expect(answer).toContainText("第一段");
  await expect(answer).not.toContainText("第二段");
  const threads = await (await page.request.get("/api/agent/threads")).json();
  const runs = await (await page.request.get(`/api/agent/threads/${threads.at(-1).id}/runs`)).json();
  expect(runs.at(-1).data.status).toBe("running");
  await page.reload();
  await page.getByRole("button", { name: "助手", exact: true }).click();
  await expect(answer).toHaveText("第一段第二段");
  await expect(answer).toHaveCount(1);
  await expect(page.getByRole("button", { name: "新会话" })).toBeEnabled();
  await page.getByLabel("给助手的消息").fill("帮我增加一个任务：明天阅读文献");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  const review = page.locator("section").filter({ has: page.getByRole("heading", { name: "核对任务草稿" }) });
  await expect(review).toBeVisible();
  expect(await (await page.request.get("/api/tasks")).json()).toHaveLength(0);
  await expect(review.getByText("原文截止描述：明天")).toBeVisible();
  await expect(review.getByLabel("确认后的截止时间")).toHaveValue("");
  await review.getByLabel("标题", { exact: true }).fill("阅读两篇文献");
  await review.getByLabel("要求", { exact: true }).fill("记录关键结论");
  await review.getByRole("button", { name: "校对完成，准备保存" }).click();
  expect(await (await page.request.get("/api/tasks")).json()).toHaveLength(0);
  await review.getByRole("button", { name: "确认保存", exact: true }).click();
  await expect(review).toHaveCount(0);
  await page.getByRole("button", { name: "待办与日程", exact: true }).click();
  await expect(page.getByRole("heading", { name: "阅读两篇文献", exact: true })).toHaveCount(1);
  await page.reload();
  await page.getByRole("button", { name: "待办与日程", exact: true }).click();
  await expect(page.getByRole("heading", { name: "阅读两篇文献", exact: true })).toHaveCount(1);
  const tasks = await (await page.request.get("/api/tasks")).json();
  expect(tasks).toHaveLength(1);
  expect(tasks[0].data.requirements).toEqual(["记录关键结论"]);
  expect(tasks[0].data.due_at).toBeNull();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true);
});
